"""Record the bundled sample results into samples/results/<id>.json.

Runs the real pipeline against live Open-Meteo data. If a usable Groq key is configured (.env or the key saved in
the app) the 72-hour plan is written by Groq. Without a key the plan is generated by simple rules and the file is
labelled advisory_source = "rule-based-offline" so nobody mistakes it for an AI answer.

Usage:   python scripts/record_samples.py            (from the project folder, with the venv active)
         python scripts/record_samples.py --offline  (force the rule-based plan)
"""
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import db, geo, keys, pipeline  # noqa: E402
from app.config import S  # noqa: E402
from app.errors import AppError  # noqa: E402


def rule_based_advisory(r: dict) -> dict:
    f, l, rain, prof = r["flood"], r["landslide"], r["rain"], r["asset_profile"]
    name = r["location"]["name"]
    calm = f["score"] < 25 and l["score"] < 25
    disch = (f"Peak river discharge near {name} is {f['peak_discharge_m3s']} m³/s, "
             f"{f['surge_ratio']}x the recent median, against a flood threshold of {f['threshold_m3s']} m³/s."
             if f["discharge_available"] else "No river channel is modelled at this grid cell, so the flood score rests on rainfall alone.")
    adv = {
        "headline": (f"{name}: no major flood or landslide trigger in the 7-day forecast." if calm
                     else f"{name}: {f['tier']} flood risk and {l['tier']} landslide susceptibility this week."),
        "flood_summary": f"{disch} Forecast rain totals {rain['total_7d_mm']} mm over 7 days (wettest day {rain['max_daily_mm']} mm).",
        "landslide_summary": (f"Terrain is {l['terrain_class'].lower()} with {r['location']['terrain']['relief_m']} m of relief nearby. "
                              f"Peak soil moisture is {l['soil_moisture_peak']} m³/m³ and the landslide score is {l['score']}/100."),
        "immediate_24h_actions": [
            "Check the IMD district warning and the CWC river bulletin each morning and evening.",
            "Keep a torch, power bank, drinking water and basic medicines in one bag.",
            "Note which road or lane floods first and agree on an alternative route.",
        ],
        "next_48_72h_actions": [
            "Re-check this forecast daily; discharge and rain forecasts shift as new model runs arrive.",
            "Clear drains, culverts and gutters near the house or field before any rain band arrives.",
        ],
        "agri_livestock_steps": [
            "Move seed, fertiliser and harvested produce above likely water level or under cover.",
            "Keep fodder and clean drinking water stocked for animals for at least three days.",
            "Open field drains so standing water can leave quickly after heavy rain.",
        ],
        "evacuation_checklist": [
            "Agree a meeting point on high ground and tell every family member.",
            "Keep Aadhaar, land papers, bank passbook and insurance copies in a waterproof bag.",
            "Save 112, 108 and the district control room number on every phone.",
            "Know who in the neighbourhood needs help to move (elderly, sick, young children).",
        ],
        "confidence_note": "Rule-based plan recorded without a live AI call. Scores come from the same live data.",
    }
    if "Hill" in prof:
        adv["immediate_24h_actions"].append("Avoid slopes and road cuttings during and after heavy rain; watch for new cracks, tilting trees and muddy springs.")
        adv["evacuation_checklist"].append("If the ground shows cracks or a stream turns muddy, leave the slope at once without waiting for an order.")
    if not calm:
        adv["immediate_24h_actions"].insert(0, "Move vehicles, cattle and valuables away from the river bank and low ground.")
    return adv


async def record(meta: dict, offline: bool) -> dict:
    async with geo.new_client() as client:
        r = await pipeline.gather(client, meta["input_text"], meta["asset_profile"])
    use_ai = (not offline) and keys.resolve_key()[0]
    if use_ai:
        await pipeline.strategist(r)
    else:
        r["advisory"] = rule_based_advisory(r)
        r["advisory_source"] = "rule-based-offline"
        r["model"] = None
        r["agents"].append({"step": 4, "name": dict(pipeline.AGENTS)[4], "status": "done", "ms": 0,
                            "summary": "Rule-based plan (no Groq key was set when this sample was recorded)."})
    return r


async def main():
    offline = "--offline" in sys.argv
    db.init_db()
    out = ROOT / "samples" / "results"
    out.mkdir(exist_ok=True)
    for p in sorted((ROOT / "samples").glob("*.json")):
        meta = json.loads(p.read_text(encoding="utf-8"))
        try:
            r = await record(meta, offline)
        except AppError as e:
            print(f"FAILED {meta['id']}: {e.message}")
            continue
        (out / f"{meta['id']}.json").write_text(json.dumps(r, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"recorded {meta['id']}: flood {r['flood']['score']} landslide {r['landslide']['score']} via {r['advisory_source']}")


if __name__ == "__main__":
    asyncio.run(main())
